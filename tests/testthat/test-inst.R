  expect_equal(a$Start, c(40, 95))
  fa <- i$fetch_fulls_annots(c("W", "N2"))
  expect_equal(fa$Class, c("W", "N2", "W"))
  expect_identical(i$fetch_full_annots("W"), i$fetch_fulls_annots("W"))

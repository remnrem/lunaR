test_that("signal access: data, slice, slices", {
  skip_if_no_lunapi()
  i <- fixture_inst()
  d <- i$data(c("EEG", "EMG"), time = TRUE)
  expect_equal(names(d), c("T", "EEG", "EMG"))
  expect_equal(nrow(d), DUR * SR)
  expect_equal(d$T[1:2], c(0, 1 / SR))
  x <- fixture_signals()$EEG
  expect_equal(d$EEG, x, tolerance = 1e-2)            # EDF 16-bit quantization
  a <- i$data("EEG", annots = "arousal", time = TRUE)
  ta <- a$T[a$arousal == 1]
  expect_true(all((ta >= 40 & ta < 45) | (ta >= 95 & ta < 97)))
  expect_equal(length(ta), 7 * SR)
  i$epoch()
  m <- i$e2i(2:3)
  s1 <- i$slice(m, "EEG", time = TRUE)
  expect_equal(nrow(s1), 60 * SR)
  expect_equal(s1$T[1], 30)
  s2 <- i$slices(m, "EEG")
  expect_length(s2, 2)
  expect_equal(nrow(s2[[2]]), 30 * SR)
  expect_error(i$data("NOPE"), "unknown channel", class = "luna_bad_channel")
  expect_error(i$data("EEG", annots = "zz"), "unknown annotation", class = "luna_bad_annot")
})

test_that("in-memory signals and annotations", {
  skip_if_no_lunapi()
  p <- quiet_proj()
  i <- p$empty_inst("mem", nr = 60, rs = 1)
  i$insert_signal("S", rnorm(60 * 50), 50)
  expect_equal(i$channels()$Channels, "S")
  expect_error(i$insert_signal("S", rnorm(10), 50), "already exists", class = "luna_error")
  expect_error(i$insert_signal("T", c(1, NA), 50), "missing values", class = "luna_error")
  i$insert_annot("ev", list(c(1, 2), c(10, 12.5)))
  expect_equal(i$fetch_annots("ev")$Stop, c(2, 12.5))
  i$insert_annot("ev2", data.frame(a = 5, b = 6))
  expect_equal(i$fetch_annots("ev2")$Start, 5)
  expect_error(i$insert_annot("bad", list(c(3, 1))), "stop before a start", class = "luna_error")
  i$update_signal("S", rep(0, 60 * 50))
  expect_true(all(abs(i$data("S")$S) < 1e-3))
  expect_error(p$empty_inst("x", nr = -1, rs = 1), "non-negative", class = "luna_error")
})


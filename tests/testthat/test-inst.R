test_that("eval() returns strata and tables are typed", {
  skip_if_no_lunapi()
  i <- fixture_inst()
  s <- i$eval(c("EPOCH dur=30", "PSD sig=EEG max=20 spectrum"))
  expect_equal(names(s), c("Command", "Strata"))
  expect_true(all(c("EPOCH", "PSD") %in% s$Command))
  expect_equal(i$table("EPOCH")$NE, 4L)
  psd <- i$table("PSD", "CH_F")
  expect_s3_class(psd, "data.frame")
  expect_type(psd$F, "double")
  expect_type(psd$CH, "character")
  expect_false(any(vapply(psd, is.list, TRUE)))
  expect_equal(psd$F[which.max(psd$PSD)], 10, tolerance = 0.5)
  expect_identical(i$table("PSD", c("F", "CH")), psd)
  expect_true("ALPHA" %in% i$table("PSD", "B_CH")$B)
  expect_false(i$empty_result_set())
})

test_that("missing tables and bad commands give luna errors", {
  skip_if_no_lunapi()
  i <- fixture_inst()
  i$eval("PSD sig=EEG max=20")
  expect_error(i$table("PSD", "CH_F"), "available for PSD: B_CH, CH", class = "luna_no_table")
  expect_error(i$table("SPINDLES", "CH"), "commands with output: PSD", class = "luna_no_table")
  e <- expect_error(i$eval("NOTACOMMAND x=1"), class = "luna_error")
  expect_match(conditionMessage(e), "did not recognize command: NOTACOMMAND")
  expect_false(grepl("py_last_error", conditionMessage(e)))
  expect_false(is.null(e$parent))
  i$eval("HEADERS")                                  # engine still usable
  expect_equal(nrow(i$table("HEADERS", "CH")), 2)
  i$eval("DUMP-MASK")                                # "-" or "_" both work
  expect_equal(nrow(i$table("DUMP-MASK", "E")), 4)
  expect_identical(i$table("DUMP_MASK", "E"), i$table("DUMP-MASK", "E"))
})

test_that("proc() returns a stable ProcResult", {
  skip_if_no_lunapi()
  i <- fixture_inst()
  r <- i$proc("EPOCH & DUMP-MASK & PSD sig=EEG max=20 spectrum")
  expect_output(print(r), "ProcResult: ")
  expect_true("DUMP_MASK: E" %in% r$keys())
  expect_equal(nrow(r[["DUMP_MASK: E"]]), 4)
  expect_identical(r$table("DUMP-MASK", "E"), r[["DUMP_MASK: E"]])
  expect_identical(r[[c("PSD", "CH_F")]], r$table("PSD", "CH_F"))
  expect_true(r$has_table("PSD", "CH"))
  expect_false(r$has_table("PSD", "CH_E"))
  expect_null(r$get("PSD: CH_E"))
  expect_equal(names(r), r$keys())
  expect_equal(length(r), nrow(r$strata()))
  expect_true(r$ok)
  expect_error(r[["nonsense"]], "available tables", class = "luna_no_table")
  i$eval("HEADERS")                                  # later commands ...
  expect_equal(nrow(r$table("PSD", "CH_F")), 79)     # ... do not change r
  q <- i$silent_proc("HEADERS")
  expect_equal(q$commands()$Command, "HEADERS")
})


test_that("lp$proj returns one shared project and reports versions", {
  skip_if_no_lunapi()
  expect_message(p1 <- lp$proj(), "initiated lunapi")
  p2 <- lp$proj(verbose = FALSE)
  expect_identical(p1, p2)
  expect_false(p1$is_silenced())       # as in lunapi, proj() enables output
  p1$silence(TRUE)
  expect_true(p1$is_silenced())
  v <- lp$version()
  expect_named(v, c("lunapi", "luna"))
  expect_true(lunapi_available())
  expect_output(cfg <- luna_config(), "status  : ok")
  expect_true(cfg$available)
})

test_that("sample lists load and index from 1", {
  skip_if_no_lunapi()
  f <- luna_fixture()
  p <- quiet_proj()
  expect_message(n <- p$sample_list(f$lst), "read 2 individuals")
  expect_equal(n, 2L)
  expect_equal(p$nobs(), 2L)
  sl <- p$sample_list()
  expect_equal(names(sl), c("ID", "EDF", "Annotations"))
  expect_equal(sl$ID, c("subj1", "subj2"))
  expect_equal(sl$Annotations[1], f$annot)
  expect_equal(p$get_n("subj2"), 2L)
  expect_true(is.na(p$get_n("nobody")))
  expect_equal(p$get_id(1), "subj1")
  expect_equal(p$get_edf("subj2"), f$edf)
  expect_equal(p$get_annots(1), f$annot)
  v <- p$validate()
  expect_true(all(v$Valid))
  expect_error(p$sample_list("nope.lst"), "cannot find sample list", class = "luna_error")
})

test_that("inst() takes an index or an ID", {
  skip_if_no_lunapi()
  p <- fixture_proj()
  expect_equal(p$inst(2)$id(), "subj2")
  expect_equal(p$inst("subj1")$id(), "subj1")
  expect_equal(p$inst(1)$channels()$Channels, c("EEG", "EMG"))
  expect_error(p$inst(3), "index out of bounds: sample list has 2", class = "luna_error")
  expect_error(p$inst(0), "out of bounds", class = "luna_error")
  e <- p$inst("newid")                         # not in the list: empty instance
  expect_equal(e$id(), "newid")
})

test_that("proc() runs across the sample list", {
  skip_if_no_lunapi()
  p <- fixture_proj()
  r <- p$proc("HEADERS & PSD sig=EEG max=20 spectrum")
  expect_s3_class(r, "ProcResult")
  expect_true(all(c("HEADERS: BL", "HEADERS: CH", "PSD: CH_F") %in% r$keys()))
  expect_equal(r[["HEADERS: BL"]]$ID, c("subj1", "subj2"))
  expect_equal(nrow(r$table("HEADERS", "CH")), 4)
  expect_equal(sort(unique(p$table("PSD", c("F", "CH"))$ID)), c("subj1", "subj2"))
  expect_equal(p$strata()$Command[1], "HEADERS")
  expect_true("PSD" %in% p$variables("PSD", "CH_F"))
})

test_that("a record that cannot be loaded stops proc(), as in lunapi", {
  skip_if_no_lunapi()
  f <- luna_fixture()
  lst <- withr::local_tempfile(fileext = ".lst")
  writeLines(c(readLines(f$lst), paste("bad", file.path(f$dir, "missing.edf"), sep = "\t")), lst)
  p <- quiet_proj()
  suppressMessages(p$sample_list(lst))
  expect_false(all(p$validate()$Valid))
  expect_error(p$proc("HEADERS"), "cannot find", class = "luna_error")
  suppressMessages(p$sample_list(f$lst))
  expect_equal(nrow(p$proc("HEADERS")[["HEADERS: BL"]]), 2)   # engine recovered
})

test_that("project variables: vars, clear_vars, include", {
  skip_if_no_lunapi()
  p <- quiet_proj()
  p$vars("foo", "bar")
  expect_equal(p$var("foo"), "bar")
  p$vars(list(a1 = "x", a2 = 2, b = TRUE))
  expect_equal(p$vars("a2"), "2")
  expect_equal(p$vars("b"), "1")
  expect_equal(p$vars(c("a1", "a2")), list(a1 = "x", a2 = "2"))
  expect_true(all(c("foo", "a1") %in% names(p$vars())))
  p$clear_vars("a1")
  expect_null(p$var("a1"))
  pf <- withr::local_tempfile()
  writeLines("pfvar\thello", pf)
  p$include(pf)
  expect_equal(p$var("pfvar"), "hello")
  p$clear_vars()
  expect_null(p$var("foo"))
  expect_null(p$var("pfvar"))
})

test_that("variables are substituted in commands", {
  skip_if_no_lunapi()
  p <- fixture_proj()
  p$vars("mysig", "EMG")
  i <- p$inst(1)
  i$eval("HEADERS sig=${mysig}")
  expect_equal(i$table("HEADERS", "CH")$CH, "EMG")
  p$clear_vars()
})

test_that("import_db reads a Luna output database", {
  skip_if_no_lunapi()
  f <- luna_fixture()
  luna_bin <- Sys.which("luna")
  skip_if(!nzchar(luna_bin), "luna command-line tool not available to write a .db")
  db <- file.path(f$dir, "out.db")
  unlink(db)
  system2(luna_bin, c(f$lst, "-o", db, "-s", shQuote("HEADERS")), stdout = FALSE, stderr = FALSE)
  skip_if(!file.exists(db), "could not create database")
  p <- quiet_proj()
  ids <- p$import_db(db)
  expect_setequal(ids, c("subj1", "subj2"))
  expect_setequal(p$table("HEADERS")$ID, c("subj1", "subj2"))
  p$import_db(db, s = "subj2")
  expect_equal(p$table("HEADERS")$ID, "subj2")
})
